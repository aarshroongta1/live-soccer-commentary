"""Rebuild the review catalog and six causal visual frames; makes no API calls."""

import hashlib
import json
import subprocess
from pathlib import Path

import cv2
import imageio_ffmpeg

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    source = ROOT / "web/public/soccer-commentary/live-search-run.json"
    saved = json.loads(source.read_text())
    line = next(item for item in saved["delivery"] if item["id"] == "context")
    fact = next(item["fact"] for item in saved["events"] if item["type"] == "fact_selected")
    footage = ROOT / "clips/demo-sources/barcelona-bayern-messi.mp4"
    data = {
        "id": "ballard-context-v1",
        "title": "Sunderland vs Arsenal",
        "video_url": (
            "https://soccer-commentary-demo.vercel.app/soccer-commentary/ballard-live-replay.mp4"
        ),
        "proposed": line["text"],
        "start_s": line["at_s"],
        "end_s": line["end_s"],
        "duration_s": 20,
        "source_run_id": saved["run_id"],
        "source_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
        "source_origin": (
            "Recorded model output and generated voice from the existing commentary pipeline. "
            "Imported into Trajectory; not newly generated by Trajectory."
        ),
        "fact": fact,
        "transfer": {
            "id": "messi-finish-v1",
            "title": "Barcelona vs Bayern",
            "video_url": "/editor-review/messi.mp4",
            "cutoff_s": 15.0,
            "frame_times_s": [7.5, 9.0, 10.5, 12.0, 13.5, 15.0],
            "source_sha256": hashlib.sha256(footage.read_bytes()).hexdigest(),
            "reviewed_identity": (
                "This is the retained Barcelona–Bayern clip from 6 May 2015. "
                "Barcelona's number 10 is Lionel Messi, as identified in the project's "
                "previous manual footage review. Identity is supplied, not inferred anew."
            ),
            "research": [
                {
                    "id": "uefa-appearance",
                    "text": "Messi was poised for his 100th appearance in UEFA competition.",
                    "url": "https://www.uefa.com/uefachampionsleague/news/"
                    "0221-0e9b4410dadd-a53b12c8f28f-1000--barcelona-v-bayern-munchen-preview/",
                    "published": "2015-05-05",
                },
                {
                    "id": "barcelona-form",
                    "text": (
                        "Barcelona entered the match after scoring 14 goals in their last "
                        "two games and keeping five consecutive clean sheets."
                    ),
                    "url": "https://www.uefa.com/uefachampionsleague/news/"
                    "0221-0e9b4410dadd-a53b12c8f28f-1000--barcelona-v-bayern-munchen-preview/",
                    "published": "2015-05-05",
                },
                {
                    "id": "guardiola-return",
                    "text": (
                        "Bayern coach Josep Guardiola was returning to Barcelona for "
                        "the first time with Bayern, after four years coaching Barcelona."
                    ),
                    "url": "https://www.uefa.com/uefachampionsleague/news/"
                    "0221-0e9b4410dadd-a53b12c8f28f-1000--barcelona-v-bayern-munchen-preview/",
                    "published": "2015-05-05",
                },
            ],
            "research_limit": (
                "Read from the current UEFA page, published 5 May and marked updated "
                "28 May 2015. Selected facts concern pre-match history; an archived "
                "match-time version was not checked. Both arms receive identical facts."
            ),
        },
    }
    frames = ROOT / "runs/commentary-editor/frames"
    frames.mkdir(parents=True, exist_ok=True)
    capture = cv2.VideoCapture(str(footage))
    try:
        for timestamp in data["transfer"]["frame_times_s"]:
            capture.set(cv2.CAP_PROP_POS_MSEC, timestamp * 1000)
            ok, frame = capture.read()
            if not ok:
                raise ValueError("Could not decode a selected frame")
            frame = cv2.resize(frame, (512, 288))
            if not cv2.imwrite(
                str(frames / f"{timestamp:.1f}.jpg"), frame, [cv2.IMWRITE_JPEG_QUALITY, 70]
            ):
                raise ValueError("Could not save a selected frame")
    finally:
        capture.release()
    video = ROOT / "web/public/editor-review/messi.mp4"
    video.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        [
            imageio_ffmpeg.get_ffmpeg_exe(),
            "-y",
            "-i",
            str(footage),
            "-t",
            "17",
            "-an",
            "-vf",
            "scale=640:-2",
            "-c:v",
            "libx264",
            "-preset",
            "fast",
            "-crf",
            "25",
            "-movflags",
            "+faststart",
            str(video),
        ],
        check=True,
        capture_output=True,
    )
    (ROOT / "web/data/editor-review.json").write_text(
        json.dumps(data, indent=2, ensure_ascii=False) + "\n"
    )
    print("Prepared one recorded proposal, six visual frames, and muted transfer footage.")


if __name__ == "__main__":
    main()
